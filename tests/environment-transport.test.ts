import { describe, it, expect } from "vitest";
import { validateProjectSettings } from "../src/host/desktop-state";
const row = (value: string, runtime = true, key = "AUDIT_BIG") => ({
  key,
  value,
  runtime,
  secret: true,
});
const check = (env: ReturnType<typeof row>[]) =>
  validateProjectSettings({ executable: "goga", profile: "", env });
describe("runtime environment transport validation", () => {
  it.each(["x".repeat(50000), "я".repeat(12000), "🙂".repeat(4500)])(
    "rejects an encoded payload too large for Docker without its contents",
    (value) => {
      let message = "";
      try {
        check([row(value)]);
      } catch (e) {
        message = (e as Error).message;
      }
      expect(message).toMatch(/runtime.*Docker|Docker.*runtime/);
      expect(message).not.toContain(value);
    },
  );
  it("rejects combined runtime entries even when individual entries fit", () => {
    expect(() =>
      check([
        row("a".repeat(30000), true, "AUDIT_A"),
        row("b".repeat(30000), true, "AUDIT_B"),
      ]),
    ).toThrow(/runtime|Docker/);
  });
  it.each(["a\ud800b", "a\udfffb"])(
    "rejects unpaired UTF-16, including host-only values",
    (value) => {
      for (const runtime of [false, true])
        expect(() => check([row(value, runtime)])).toThrow(/Unicode|UTF-16/);
    },
  );
  it("preserves valid pairs, controls allowed as data, quotes, equals and literal slash-n", () => {
    const env = [row('  Привет 🙂\t"quoted"\\n=$HOME;a=b\u0001')];
    expect(check(env).env).toEqual(env);
  });
  it("excludes runtime OFF rows from the codec size", () => {
    const env = [row("x".repeat(65536), false)];
    expect(check(env).env).toEqual(env);
  });
  it("accepts the last supported payload line and rejects the next base64 quantum", () => {
    expect(check([row("x".repeat(49124))]).env[0].value.length).toBe(49124);
    expect(() => check([row("x".repeat(49125))])).toThrow(/runtime|Docker/);
  });
});

// Generated by the supported Goga Python encoder, not this implementation.
import golden from "./fixtures/goga-env-codec.json";
import { environmentTransportSize } from "../src/shared/environment-transport";
it.each(golden)(
  "matches Python ensure_ascii/base64 size: $label",
  ({ rows, expected }) => {
    expect(environmentTransportSize(rows)).toEqual(expected);
  },
);
