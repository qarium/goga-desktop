import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../locales/", import.meta.url));
export const output = fileURLToPath(
  new URL("../src/shared/locale-packs.generated.ts", import.meta.url),
);
const read = (path) => JSON.parse(readFileSync(path, "utf8"));
const parts = (s) =>
  [...new Set([...s.matchAll(/\{([a-zA-Z_]\w*)\}/g)].map((m) => m[1]))]
    .sort()
    .join(",");
const plural = /_(zero|one|two|few|many|other)$/;
export function generate(directory = root) {
  const dirs = readdirSync(directory, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  if (!dirs.includes("en")) throw Error("Missing English reference pack");
  const signatures = new Map(),
    imports = [],
    entries = [],
    natives = [],
    keyTypes = [];
  for (const tag of ["en", ...dirs.filter((d) => d !== "en")]) {
    const folder = join(directory, tag),
      manifest = read(join(folder, "manifest.json"));
    if (
      !/^[a-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(tag) ||
      Intl.getCanonicalLocales(tag)[0] !== tag ||
      manifest.tag !== tag ||
      !manifest.name?.trim()
    )
      throw Error("Invalid locale manifest: " + tag);
    const domains = readdirSync(folder)
      .filter((f) => f.endsWith(".json") && f !== "manifest.json")
      .sort();
    const signature = {},
      forms = {},
      resources = [];
    for (const file of domains) {
      const domain = file.slice(0, -5);
      if (!/^[a-zA-Z][a-zA-Z0-9-]*$/.test(domain))
        throw Error("Invalid domain: " + file);
      const dict = read(join(folder, file)),
        id = "pack" + imports.length;
      if (!dict || Array.isArray(dict) || typeof dict !== "object")
        throw Error("Expected message dictionary: " + file);
      imports.push(
        "import " + id + ' from "../../locales/' + tag + "/" + file + '";',
      );
      if (tag === "en")
        keyTypes.push("`" + domain + ".${keyof typeof " + id + " & string}`");
      resources.push('...prefix("' + domain + '", ' + id + ")");
      for (const [key, value] of Object.entries(dict)) {
        if (
          !/^[A-Za-z0-9][\w.-]*$/.test(key) ||
          typeof value !== "string" ||
          value.trim().length === 0
        )
          throw Error("Invalid message: " + [tag, domain, key].join("."));
        const k = domain + "." + key,
          base = k.replace(plural, ""),
          form = k.match(plural)?.[1];
        if (form) (forms[base] ??= new Set()).add(form);
        const sig = (form ? "plural:" : "") + parts(value);
        if (base in signature && signature[base] !== sig)
          throw Error("Inconsistent forms: " + base);
        signature[base] = sig;
      }
    }
    for (const [base, present] of Object.entries(forms))
      for (const form of new Intl.PluralRules(tag).resolvedOptions()
        .pluralCategories)
        if (!present.has(form))
          throw Error("Missing " + tag + " " + base + "_" + form);
    signatures.set(tag, signature);
    entries.push(
      '  "' + tag + '": { translation: { ' + resources.join(", ") + " } }",
    );
    natives.push({ tag, name: manifest.name });
  }
  const baseline = signatures.get("en");
  for (const [tag, sig] of signatures)
    for (const key of new Set([...Object.keys(baseline), ...Object.keys(sig)]))
      if (baseline[key] !== sig[key])
        throw Error("Key/parameter mismatch: " + tag + " " + key);
  return (
    "// Generated by scripts/locales.mjs. Edit locales/<tag>/*.json instead.\n" +
    imports.join("\n") +
    "\ntype RawMessageKey = " +
    keyTypes.join(" | ") +
    ';\ntype BaseKey<K> = K extends `${infer Base}_${"zero"|"one"|"two"|"few"|"many"|"other"}` ? Base : K;\nexport type MessageKey = BaseKey<RawMessageKey>;\nconst prefix = (domain: string, dict: Record<string,string>) => Object.fromEntries(Object.entries(dict).map(([key,value])=>[domain+\'.\'+key,value]));\nexport const languages = ' +
    JSON.stringify(natives) +
    " as const;\nexport const resources = {\n" +
    entries.join(",\n") +
    "\n};\n"
  );
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const result = generate();
  if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== result)
      throw Error("Locale registry is stale. Run npm run locales:generate.");
  } else writeFileSync(output, result);
}
